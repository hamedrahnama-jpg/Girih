import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const templatesDir = path.join(rootDir, 'public', 'templates');
const outputFile = path.join(rootDir, 'src', 'publicTemplates.generated.js');
const imageExtensions = new Set(['.jpg', '.jpeg', '.png', '.webp']);

function slugify(value) {
  return String(value)
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function titleFromFilename(filename) {
  return filename.replace(/\.[^.]+$/i, '').trim();
}

function defaultGroupForTemplate(name) {
  const match = String(name).match(/(\d+)/);
  const number = match ? Number(match[1]) : 0;
  if (number >= 39 && number <= 49) return '8 Morocco';
  if (number >= 52 && number <= 65) return '8 Persian';
  if (number >= 71 && number <= 78) return '10 Tond';
  if (number >= 84 && number <= 94) return '10 Kond';
  return 'Default';
}

async function readTemplateFiles(dir, prefix = '') {
  let entries = [];
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return [];
  }

  const records = [];
  for (const entry of entries) {
    const relativePath = prefix ? `${prefix}/${entry.name}` : entry.name;
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      records.push(...(await readTemplateFiles(fullPath, relativePath)));
      continue;
    }
    const extension = path.extname(entry.name).toLowerCase();
    if (!entry.isFile() || !imageExtensions.has(extension)) continue;
    const name = titleFromFilename(entry.name);
    records.push({
      id: slugify(relativePath.replace(/\.[^.]+$/i, '')),
      name,
      filename: relativePath.replaceAll('\\', '/'),
      group: defaultGroupForTemplate(name),
    });
  }
  return records;
}

const templates = (await readTemplateFiles(templatesDir)).sort((a, b) => a.filename.localeCompare(b.filename, undefined, { numeric: true }));
const groups = [...new Set(templates.map((template) => template.group))].sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));

const source = `// Generated by scripts/generate-public-templates.mjs. Do not edit by hand.
export const PUBLIC_TEMPLATE_GROUPS = ${JSON.stringify(groups, null, 2)};

export const PUBLIC_TEMPLATE_FILES = ${JSON.stringify(templates, null, 2)};
`;

await writeFile(outputFile, source);
