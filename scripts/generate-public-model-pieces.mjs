import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const modelsDir = path.join(rootDir, 'public', 'models');
const outputFile = path.join(rootDir, 'src', 'publicModelPieces.generated.js');

const knownColors = new Map([
  ['badami', '#2f7d73'],
  ['chenari', '#8a6bb8'],
  ['giveh', '#2b7a6f'],
  ['loz', '#b86f3e'],
  ['maku', '#1f6f68'],
  ['panj', '#6e7fbd'],
  ['sekro', '#8b6f47'],
  ['separi', '#3f8c82'],
  ['setareh', '#2e8278'],
  ['setareh-shol', '#2b716a'],
  ['shamseh', '#d58a36'],
  ['shamseh-kond', '#c4812f'],
  ['shesh-band', '#1c7c74'],
  ['shesh-shol', '#2f8d7e'],
  ['sormehdan', '#526d93'],
  ['tabl', '#9a5845'],
  ['tah-borideh', '#b9455a'],
  ['taragheh', '#4076b8'],
  ['toranj', '#6f8d44'],
  ['toranj-kond', '#78914a'],
]);

const palette = ['#2f7d73', '#8a6bb8', '#b86f3e', '#6e7fbd', '#d58a36', '#526d93', '#b9455a', '#4076b8'];

function slugify(value) {
  return String(value)
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function titleFromFilename(filename) {
  return filename.replace(/\.glb$/i, '').trim();
}

function fallbackColor(id) {
  const hash = [...id].reduce((sum, char) => sum + char.charCodeAt(0), 0);
  return palette[hash % palette.length];
}

async function readPublicModelFolders() {
  const entries = await readdir(modelsDir, { withFileTypes: true });
  return entries
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
}

async function readGlbFiles(group) {
  const entries = await readdir(path.join(modelsDir, group), { withFileTypes: true });
  return entries
    .filter((entry) => entry.isFile() && entry.name.toLowerCase().endsWith('.glb'))
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
}

const groups = await readPublicModelFolders();
const pieces = [];

for (const group of groups) {
  const files = await readGlbFiles(group);
  for (const file of files) {
    const name = titleFromFilename(file);
    const id = slugify(name);
    pieces.push({
      id,
      name,
      filename: `${group}/${file}`,
      color: knownColors.get(id) || fallbackColor(id),
      group,
    });
  }
}

const source = `// Generated by scripts/generate-public-model-pieces.mjs. Do not edit by hand.
export const PUBLIC_MODEL_GROUPS = ${JSON.stringify(groups, null, 2)};

export const PUBLIC_MODEL_FILES = ${JSON.stringify(pieces, null, 2)};
`;

await writeFile(outputFile, source);
